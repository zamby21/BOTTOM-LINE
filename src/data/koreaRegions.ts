export interface RegionFlatMatch {
  sido: string;
  sigungu: string;
  dong: string;
  ri: string;
  fullLabel: string;
}

export function searchKoreaRegions(query: string, limit = 12): RegionFlatMatch[] {
  const q = query.trim().replace(/\s+/g, ' ');
  if (!q) return [];
  const tokens = q.split(' ').filter(Boolean);
  const results: RegionFlatMatch[] = [];

  for (const sido of KOREA_REGIONS) {
    for (const sigungu of sido.sigungus) {
      const sigunguLabel = `${sido.name} ${sigungu.name}`;
      if (
        tokens.every(
          (t) =>
            sido.name.includes(t) ||
            sido.shortName.includes(t) ||
            sigungu.name.includes(t)
        )
      ) {
        results.push({
          sido: sido.name,
          sigungu: sigungu.name,
          dong: '',
          ri: '',
          fullLabel: sigunguLabel,
        });
      }

      for (const dong of sigungu.dongs) {
        const dongLabel =
          sigungu.name === '세종시 전체'
            ? `${sido.name} ${dong.name}`
            : `${sido.name} ${sigungu.name} ${dong.name}`;

        if (
          tokens.every(
            (t) =>
              sido.name.includes(t) ||
              sido.shortName.includes(t) ||
              sigungu.name.includes(t) ||
              dong.name.includes(t)
          )
        ) {
          results.push({
            sido: sido.name,
            sigungu: sigungu.name,
            dong: dong.name,
            ri: '',
            fullLabel: dongLabel,
          });
        }

        if (dong.ri) {
          for (const ri of dong.ri) {
            const riLabel = `${dongLabel} ${ri}`;
            if (tokens.every((t) => riLabel.includes(t) || sido.shortName.includes(t))) {
              results.push({
                sido: sido.name,
                sigungu: sigungu.name,
                dong: dong.name,
                ri,
                fullLabel: riLabel,
              });
            }
          }
        }
      }
      if (results.length >= limit * 3) break;
    }
  }

  // Prefer more specific (dong/ri) matches first when query contains dong keyword
  results.sort((a, b) => {
    const aSpecific = a.dong ? (a.ri ? 2 : 1) : 0;
    const bSpecific = b.dong ? (b.ri ? 2 : 1) : 0;
    if (aSpecific !== bSpecific) return bSpecific - aSpecific;
    return a.fullLabel.length - b.fullLabel.length;
  });

  return results.slice(0, limit);
}

export function matchRegionFromAddressString(address: string): {
  sido: string;
  sigungu: string;
  dong: string;
  ri: string;
} {
  if (!address) return { sido: '', sigungu: '', dong: '', ri: '' };
  for (const sido of KOREA_REGIONS) {
    if (address.includes(sido.name) || address.startsWith(sido.shortName)) {
      for (const sigungu of sido.sigungus) {
        const cleanSigungu = sigungu.name === '세종시 전체' ? '' : sigungu.name;
        if (!cleanSigungu || address.includes(cleanSigungu)) {
          for (const dong of sigungu.dongs) {
            if (address.includes(dong.name)) {
              const matchedRi = dong.ri?.find((r) => address.includes(r)) || '';
              return { sido: sido.name, sigungu: sigungu.name, dong: dong.name, ri: matchedRi };
            }
          }
          if (cleanSigungu) {
            return { sido: sido.name, sigungu: sigungu.name, dong: '', ri: '' };
          }
        }
      }
      return { sido: sido.name, sigungu: '', dong: '', ri: '' };
    }
  }
  return { sido: '', sigungu: '', dong: '', ri: '' };
}
