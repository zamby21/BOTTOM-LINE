export const TAX_MAJOR_CATEGORIES: string[] = Array.from(
  new Set(TAX_INDUSTRY_TAXONOMY.map((item) => item.major))
);

export function getTaxMediumCategories(major: string): string[] {
  if (!major) return [];
  return Array.from(
    new Set(
      TAX_INDUSTRY_TAXONOMY.filter((item) => item.major === major).map((item) => item.medium)
    )
  );
}

export function getTaxSubCategories(major: string, medium: string): TaxIndustryItem[] {
  if (!major || !medium) return [];
  return TAX_INDUSTRY_TAXONOMY.filter(
    (item) => item.major === major && item.medium === medium
  );
}

export function searchTaxIndustries(query: string, limit = 15): TaxIndustryItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return TAX_INDUSTRY_TAXONOMY.filter(
    (item) =>
      item.name.toLowerCase().includes(q) ||
      item.major.toLowerCase().includes(q) ||
      item.medium.toLowerCase().includes(q) ||
      item.taxCode.includes(q) ||
      item.keywords.some((k) => k.toLowerCase().includes(q))
  ).slice(0, limit);
}

export function findTaxIndustryForCandidate(
  businessName: string,
  businessType: BusinessCategory,
  taxCode?: string
): TaxIndustryItem | undefined {
  if (taxCode) {
    const byCodeAndName = TAX_INDUSTRY_TAXONOMY.find(
      (i) => i.taxCode === taxCode && i.name === businessName
    );
    if (byCodeAndName) return byCodeAndName;
  }
  const byExactName = TAX_INDUSTRY_TAXONOMY.find((i) => i.name === businessName);
  if (byExactName) return byExactName;

  // Fallback defaults for initial presets
  const fallbackMap: Partial<Record<BusinessCategory, string>> = {
    cafe: '552301-coffee',
    restaurant: '552101-baekban',
    pub: '552403-hof-pub',
    snack: '552201-bunsik',
    bakery: '552202-bakery',
    retail: '521910-convenience',
    beauty: '930201-hair',
    entertainment: '924901-pc',
    fitness: '924102-fitness',
  };
  return TAX_INDUSTRY_TAXONOMY.find((i) => i.id === fallbackMap[businessType]);
}
